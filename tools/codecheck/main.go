// Command codecheck checks repository source files for encoding and comment
// hygiene: non-ASCII characters, UTF-8 BOM, CRLF line endings, a missing final
// newline, and noise comments such as version tags, marker sigils, change
// notes, generator attributions, and banner separators.
//
// Usage:
//
//	go run ./tools/codecheck [path ...]
//
// Paths may be files or directories; the default is the current directory.
// The desc, build, and .git directories and the LICENSE file are skipped.
// The command exits 0 when clean, 1 when findings exist, 2 on internal errors.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var sourceExtensions = map[string]bool{
	".zyx":  true,
	".c":    true,
	".h":    true,
	".go":   true,
	".py":   true,
	".ps1":  true,
	".sh":   true,
	".toml": true,
}

var skipDirs = map[string]bool{
	".git":  true,
	"desc":  true,
	"build": true,
}

var skipFiles = map[string]bool{
	"LICENSE": true,
}

var noisePatterns = []struct {
	name string
	expr *regexp.Regexp
}{
	{"version-tag", regexp.MustCompile(`(?i)\bv\d+\.\d+`)},
	{"marker-sigil", regexp.MustCompile(`\$(TODO|FIXME|XXX)\b`)},
	{"change-note", regexp.MustCompile(`(?i)\b(changed|added|removed|updated)\s+in\s+v?\d`)},
	{"generator", regexp.MustCompile(`(?i)\bgenerated by\b`)},
	{"banner", regexp.MustCompile(`^(//+\s*[=\-*#]{4,}|#\s*[=\-#*]{4,})`)},
}

func main() {
	flag.Parse()
	targets := flag.Args()
	if len(targets) == 0 {
		targets = []string{"."}
	}
	files, findings := 0, 0
	for _, target := range targets {
		err := filepath.WalkDir(target, func(path string, entry fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if entry.IsDir() {
				if skipDirs[entry.Name()] {
					return fs.SkipDir
				}
				return nil
			}
			if skipFiles[entry.Name()] || !sourceExtensions[strings.ToLower(filepath.Ext(path))] {
				return nil
			}
			files++
			findings += checkFile(path)
			return nil
		})
		if err != nil {
			fmt.Fprintln(os.Stderr, "codecheck:", err)
			os.Exit(2)
		}
	}
	if findings > 0 {
		fmt.Printf("FAIL: %d finding(s) in %d file(s)\n", findings, files)
		os.Exit(1)
	}
	fmt.Printf("OK: %d file(s) checked\n", files)
}

func checkFile(path string) int {
	data, err := os.ReadFile(path)
	if err != nil {
		fmt.Fprintln(os.Stderr, "codecheck:", err)
		return 1
	}
	findings := 0
	report := func(kind, detail string) {
		fmt.Printf("%s: %s: %s\n", path, kind, detail)
		findings++
	}
	if bytes.HasPrefix(data, []byte{0xEF, 0xBB, 0xBF}) {
		report("bom", "file starts with a UTF-8 BOM")
	}
	if bytes.ContainsRune(data, '\r') {
		report("crlf", "file contains carriage returns")
	}
	if len(data) > 0 && data[len(data)-1] != '\n' {
		report("eol", "file does not end with a newline")
	}
	scanner := bufio.NewScanner(bytes.NewReader(data))
	scanner.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	for number := 1; scanner.Scan(); number++ {
		line := scanner.Text()
		for _, r := range line {
			if r > 0x7F {
				report("non-ascii", fmt.Sprintf("line %d: %s", number, line))
				break
			}
		}
		comment := commentTail(line)
		if comment == "" {
			continue
		}
		for _, pattern := range noisePatterns {
			if pattern.expr.MatchString(comment) {
				report("noise:"+pattern.name, fmt.Sprintf("line %d: %s", number, line))
			}
		}
	}
	return findings
}

// commentTail returns the comment part of a line: the text from the first
// double slash, or the whole line when it starts with a hash. Lines without a
// comment return an empty string.
func commentTail(line string) string {
	if idx := strings.Index(line, "//"); idx >= 0 {
		return line[idx:]
	}
	if trimmed := strings.TrimSpace(line); strings.HasPrefix(trimmed, "#") {
		return trimmed
	}
	return ""
}
